    CHINESE("zh", "中文 (简体)", "🇨🇳", false),
    JAPANESE("ja", "日本語", "🇯🇵", false),
    KOREAN("ko", "한국어", "🇰🇷", false),
    HINDI("hi", "हिन्दी", "🇮🇳", false),
    PORTUGUESE("pt", "Português", "🇧🇷", false),
    ITALIAN("it", "Italiano", "🇮🇹", false),
    INDONESIAN("id", "Bahasa Indonesia", "🇮🇩", false),
    URDU("ur", "اردو", "🇵🇰", true),
    PERSIAN("fa", "فارسی", "🇮🇷", true);

    val layoutDirection: LayoutDirection
        get() = if (isRtl) LayoutDirection.Rtl else LayoutDirection.Ltr

    companion object {
        fun fromSystemLocale(): AppLanguage {
            val sysLang = Locale.getDefault().language.lowercase(Locale.ROOT)
            return entries.find { it.code == sysLang } ?: ARABIC

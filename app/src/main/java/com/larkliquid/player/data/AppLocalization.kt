enum class AppLanguage(
    val code: String,
    val nativeName: String,
    val isRtl: Boolean
) {
    ARABIC("ar", "العربية", true),
    ENGLISH("en", "English", false),
    FRENCH("fr", "Français", false),
    SPANISH("es", "Español", false),
    GERMAN("de", "Deutsch", false),
    TURKISH("tr", "Türkçe", false),
    RUSSIAN("ru", "Русский", false),
    CHINESE("zh", "中文", false),
    JAPANESE("ja", "日本語", false),
    KOREAN("ko", "한국어", false),
    HINDI("hi", "हिन्दी", false),
    PORTUGUESE("pt", "Português", false),
    ITALIAN("it", "Italiano", false),
    INDONESIAN("id", "Indonesia", false),
    URDU("ur", "اردو", true),
    PERSIAN("fa", "فارسی", true);

    val layoutDirection: LayoutDirection
        get() = if (isRtl) LayoutDirection.Rtl else LayoutDirection.Ltr

    companion object {
        /**
         * Automatically detects the phone's system language from Android Configuration / Locale
         * and switches the entire UI and RTL/LTR layout direction automatically without manual user intervention.
         */
        fun fromConfiguration(configuration: Configuration): AppLanguage {
            val locale = if (configuration.locales.isEmpty) {
                Locale.getDefault()
            } else {
                configuration.locales[0]
            }
            val sysLang = locale.language.lowercase(Locale.ROOT)
            return entries.find { it.code == sysLang } ?: ARABIC
        }

        fun fromSystemLocale(): AppLanguage {
            val sysLang = Locale.getDefault().language.lowercase(Locale.ROOT)
            return entries.find { it.code == sysLang } ?: ARABIC
        }
    }
}

